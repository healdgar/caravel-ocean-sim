// Bakes the anchor into js/anchor-iron.js. Build the source with sand3d, then bake it:
//   python third_party/sand3d-parts/... (s3d.export to a GLB, see the sand3d skill)
//   node scripts/bake-anchor.mjs anchor.glb
// The result stands in the anchor's own frame, the one the rode and the seabed rely on: Y up the
// shank, the ring's centre at (0, 0.65, 0), the crown's lowest point at y = -0.67, arms along X.
import { readFileSync, writeFileSync } from 'node:fs';
import { MeshoptSimplifier } from 'meshoptimizer';
import { bestStep, createDecimator, hardenNormals } from './safe-decimate.mjs';

const EYE_Y = 0.65, LOWEST_Y = -0.67;
const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
const unit = (v) => { const l = Math.hypot(...v); return v.map((x) => x / l); };
const cross = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
const centre = (part) => {
  const lo = [Infinity, Infinity, Infinity], hi = [-Infinity, -Infinity, -Infinity];
  for (let i = 0; i < part.indices.length; i++) for (let k = 0; k < 3; k++) {
    const v = part.positions[part.indices[i] * 3 + k];
    lo[k] = Math.min(lo[k], v); hi[k] = Math.max(hi[k], v);
  }
  return lo.map((v, k) => (v + hi[k]) / 2);
};

await MeshoptSimplifier.ready;
const decimator = createDecimator(readFileSync(process.argv[2]));
const { rows, best } = bestStep(decimator);
if (!best) throw Error(`No step passes the shape checks: ${rows.map((r) => r.triangles).join(', ')}`);
const final = decimator.finish(best), named = (name) => final.parts.find((part) => part.name === name);
const eye = centre(named('eye')), crown = centre(named('curved_crown'));
const up = unit(eye.map((v, k) => v - crown[k]));
const flukeA = centre(named('lower_fluke')), flukeB = centre(named('lower_fluke.001'));
const across = flukeA.map((v, k) => v - flukeB[k]), lean = dot(across, up);
const right = unit(across.map((v, k) => v - lean * up[k])), aft = cross(right, up);

let lowest = Infinity;
for (const part of final.parts) for (let i = 0; i < part.indices.length; i++) {
  const at = part.indices[i] * 3;
  lowest = Math.min(lowest, dot([part.positions[at] - eye[0], part.positions[at + 1] - eye[1], part.positions[at + 2] - eye[2]], up));
}
const scale = (EYE_Y - LOWEST_Y) / -lowest;
const values = [];
for (const part of final.parts) {
  const hard = hardenNormals(part);
  for (const v of hard.indices) {
    const p = [hard.positions[v * 3] - eye[0], hard.positions[v * 3 + 1] - eye[1], hard.positions[v * 3 + 2] - eye[2]];
    const n = [hard.normals[v * 3], hard.normals[v * 3 + 1], hard.normals[v * 3 + 2]];
    values.push(dot(p, right) * scale, dot(p, up) * scale + EYE_Y, dot(p, aft) * scale, dot(n, right), dot(n, up), dot(n, aft));
  }
}
const lines = [];
const text = values.map((v) => (Math.abs(v) < 5e-5 ? '0' : Number(v.toFixed(4)).toString().replace(/^(-?)0\./, '$1.')));
for (let i = 0; i < text.length; i += 72) lines.push(text.slice(i, i + 72).join(','));
writeFileSync(new URL('../js/anchor-iron.js', import.meta.url), `// Copyright (c) 2026 Six Cailloux, LLC. MIT License; see LICENSE.
// Generated by scripts/bake-anchor.mjs from third_party/sand3d-parts/old-rusted-anchor.py. Do not edit.
// ${final.triangles} triangles: position and normal per corner, in the anchor's own frame.
// Shape from "Old rusted anchor" by trivial.cat, CC BY 4.0; see THIRD_PARTY_NOTICES.md.
export const ANCHOR_IRON = Object.freeze([
${lines.join(',\n')},
]);
`);
const ys = values.filter((_, i) => i % 6 === 1), xs = values.filter((_, i) => i % 6 === 0), zs = values.filter((_, i) => i % 6 === 2);
console.log(`${final.triangles} triangles, scale ${scale.toFixed(3)}, x ${Math.min(...xs).toFixed(2)}..${Math.max(...xs).toFixed(2)}, y ${Math.min(...ys).toFixed(2)}..${Math.max(...ys).toFixed(2)}, z ${Math.min(...zs).toFixed(2)}..${Math.max(...zs).toFixed(2)}, surface error ${((final.distance / decimator.diagonal) * 100).toFixed(2)}%, outline moved ${((final.drift / decimator.diagonal) * 100).toFixed(2)}%`);

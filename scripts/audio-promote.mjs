// Offline promotion: only the explicit selected, edited auditions enter the game.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { buildReview, SAMPLES } from './audio.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
process.chdir(root);
const selection=JSON.parse(await fs.readFile('scripts/audio/review-selection.json','utf8'));
await buildReview({selection});
const checks=JSON.parse(await fs.readFile('shots/audio-review/checks.json','utf8'));
await fs.mkdir('assets/audio',{recursive:true});
const manifest={},provenance=[];
for(const c of checks){
  const recipe=SAMPLES.find(s=>s.id===c.id);
  const suffix=c.edit?'-edit-'+createHash('sha256').update(JSON.stringify(c.edit)).digest('hex').slice(0,8):'';
  const input=`shots/audio-review/${c.id}-${c.take}${suffix}.wav`,output=`assets/audio/${c.id}.mp3`;
  // LAME's gapless metadata preserves the edited loop duration on Web Audio decode.
  execFileSync('ffmpeg',['-v','error','-y','-i',input,'-map_metadata','-1','-c:a','libmp3lame','-q:a','4',output]);
  const bytes=await fs.readFile(output);
  manifest[c.id]={url:output,loop:recipe.loop,seconds:c.seconds};
  provenance.push({id:c.id,take:c.take,edit:c.edit??null,seconds:c.seconds,loop:recipe.loop,
    provider:'ElevenLabs',model:'eleven_text_to_sound_v2',sha256:createHash('sha256').update(bytes).digest('hex'),bytes:bytes.length});
}
await fs.writeFile('js/audio-assets.js','// Selected ElevenLabs sound effects; regenerated by scripts/audio-promote.mjs.\nexport const SOUND_ASSETS = '+JSON.stringify(manifest,null,2)+';\n');
await fs.writeFile('assets/audio/provenance.json',JSON.stringify(provenance,null,2)+'\n');
console.log(`Promoted ${checks.length} sounds (${provenance.reduce((s,a)=>s+a.bytes,0)} bytes).`);

#!/usr/bin/env node
// Project-local, journaled offline authoring. No provider access from the game.
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {resolveAudioKey,generateSound,buildReview,reviewWave,editAudio} from './audio.mjs';
import {paidRequest,speechRequest,CAST} from './voices.mjs';

const GUNNERY_AUTHOR_ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const GUNNERY_AUTHOR_DIR=path.join(GUNNERY_AUTHOR_ROOT,'.audio/gunnery');
export const GUNNERY_RECIPES=JSON.parse(await fs.readFile(new URL('./audio/gunnery.json',import.meta.url),'utf8'));
const gunneryHash=bytes=>createHash('sha256').update(bytes).digest('hex');

export async function generateGunneryAudio({take='01',ids}={}){
  if(!/^[a-z0-9-]+$/.test(take))throw Error('Invalid explicit take name.');
  const key=await resolveAudioKey(),wanted=ids?new Set(ids.split(',')):null;
  const selected=JSON.parse(await fs.readFile(new URL('./audio/voice-selection.json',import.meta.url),'utf8'));
  for(const sound of GUNNERY_RECIPES.sounds.filter(s=>!wanted||wanted.has(s.id))){
    const result=await generateSound(sound,{key,dir:GUNNERY_AUTHOR_DIR,take});
    console.log(JSON.stringify({id:result.id,take,reused:result.reused,credits:result.credits}));
  }
  for(const line of GUNNERY_RECIPES.speech.filter(s=>!wanted||wanted.has(s.id))){
    const voiceId=line.speaker==='captain'?selected.captain.voiceId:CAST.crew.find(p=>p.id===line.speaker)?.voiceId;
    if(!voiceId)throw Error('No existing selected voice for '+line.speaker);
    const result=await paidRequest(line.id+'-'+take,`/v1/text-to-speech/${voiceId}?output_format=mp3_44100_128`,speechRequest(line.text,{seed:1805}),{key,dir:GUNNERY_AUTHOR_DIR,audio:true});
    console.log(JSON.stringify({id:line.id,take,reused:result.reused,credits:result.credits}));
  }
}

export async function promoteGunneryAudio({take='01'}={}){
  const out=path.join(GUNNERY_AUTHOR_ROOT,'assets/audio/gunnery');
  await fs.mkdir(out,{recursive:true});
  const assets={},provenance=[];
  const selection=JSON.parse(await fs.readFile(new URL('./audio/gunnery-selection.json',import.meta.url),'utf8'));
  for(const recipe of [...GUNNERY_RECIPES.sounds,...GUNNERY_RECIPES.speech]){
    const id=recipe.id,selectedTake=selection[id]?.take??take,input=path.join(GUNNERY_AUTHOR_DIR,id+'-'+selectedTake+'.mp3');
    const record=JSON.parse(await fs.readFile(path.join(GUNNERY_AUTHOR_DIR,id+'-'+selectedTake+'.json'),'utf8'));
    if(record.status!=='complete'||record.sha256!==gunneryHash(await fs.readFile(input)))throw Error('Incomplete or modified source: '+id);
    const output=path.join(out,id+'.mp3');
    // Preserve blast transient crest factor: fixed headroom, no loudnorm compression.
    // Mechanical and speech levels remain quieter than the report in the game.
    const pcm=recipe.text?null:execFileSync('ffmpeg',['-v','error','-i',input,'-af','highpass=f=28','-f','f32le','-ac','2','-ar','44100','pipe:1'],{maxBuffer:16*1024*1024});
    const edit=selection[id]?.edit;
    const prepared=pcm?reviewWave(editAudio(pcm,edit)):null;
    const filter=recipe.text?'highpass=f=70,loudnorm=I=-19:TP=-4:LRA=9':'highpass=f=28,volume='+(prepared.gainDb-1).toFixed(4)+'dB';
    if(edit){
      execFileSync('ffmpeg',['-v','error','-y','-f','wav','-i','pipe:0','-map_metadata','-1','-af','volume=-1dB','-ac','1','-ar','44100','-c:a','libmp3lame','-q:a','4',output],{input:prepared.wav});
    }else execFileSync('ffmpeg',['-v','error','-y','-i',input,'-map_metadata','-1','-af',filter,'-ac','1','-ar','44100','-c:a','libmp3lame','-q:a','4',output]);
    const seconds=Number(execFileSync('ffprobe',['-v','error','-show_entries','format=duration','-of','csv=p=0',output],{encoding:'utf8'}).trim());
    const bytes=await fs.readFile(output);
    assets[id]={url:'assets/audio/gunnery/'+id+'.mp3',loop:false,seconds};
    provenance.push({id,take:selectedTake,edit:edit??null,provider:'ElevenLabs',model:record.request.model_id,voiceId:record.route?.split('/').pop()?.split('?')[0]??null,text:recipe.text?record.request.text:null,prompt:recipe.text?null:record.request.text,seconds,sourceSha256:record.sha256,sha256:gunneryHash(bytes),bytes:bytes.length,processing:edit?'highpass=28 Hz; fixed -7 dBFS peak; trim/fade as specified':filter,credits:record.credits??null});
  }
  await fs.writeFile(path.join(out,'provenance.json'),JSON.stringify(provenance,null,2)+'\n');
  await fs.writeFile(path.join(GUNNERY_AUTHOR_ROOT,'js/gunnery-audio-assets.js'),'// Offline authored; generated by scripts/gunnery-audio.mjs promote.\nexport const GUNNERY_AUDIO_ASSETS = '+JSON.stringify(assets,null,2)+';\n');
  console.log(JSON.stringify({promoted:provenance.length,bytes:provenance.reduce((s,a)=>s+a.bytes,0),assets}));
}

async function gunneryAuthorMain(args){
  const [command='plan',take='01',ids]=args;
  if(command==='plan')console.log(JSON.stringify(GUNNERY_RECIPES,null,2));
  else if(command==='generate')await generateGunneryAudio({take,ids});
  else if(command==='promote')await promoteGunneryAudio({take});
  else if(command==='review')console.log(JSON.stringify(await buildReview({take,samples:GUNNERY_RECIPES.sounds,dir:GUNNERY_AUTHOR_DIR,out:path.join(GUNNERY_AUTHOR_ROOT,'shots/gunnery-audio-review')})));
  else throw Error('Use plan, generate [take] [comma-separated IDs], review [take] or promote [take].');
}
if(process.argv[1]&&import.meta.url===pathToFileURL(path.resolve(process.argv[1])).href)gunneryAuthorMain(process.argv.slice(2)).catch(e=>{console.error(e.message);process.exitCode=1;});
